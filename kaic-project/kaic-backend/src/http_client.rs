//! Одно место, где создаются HTTP-клиенты, и одно место, где живут их
//! таймауты.
//!
//! Зачем модуль, а не три вызова `Client::builder()` по месту: до него в
//! коде было три независимых `reqwest::Client::new()`, и ни один из них не
//! имел таймаута вообще. Умолчание `reqwest` — ждать бесконечно. Локально
//! это терпимо: LM Studio либо отвечает, либо процесс убивают руками. Но
//! отказ вида «соединение установлено, ответа нет» подвешивает задачу
//! навсегда — статус остаётся `InProgress`, `GenerationGuard` не
//! освобождается, и модель нельзя вытеснить, потому что она числится
//! занятой. Одна такая задача выедает половину `MAX_CONCURRENT_TASKS`
//! до перезапуска процесса.
//!
//! Три клиента ходят к трём разным адресатам с разной ценой ожидания,
//! поэтому таймаут у каждого свой — но выведены они здесь, рядом, чтобы
//! следующий клиент не появился снова без таймаута.

use std::time::Duration;

/// Потолок на установление соединения — отдельно от потолка на ответ.
///
/// Различие существенно: «не удалось достучаться» и «модель долго думает» —
/// разные отказы, и мерить их одним числом значит либо рубить работающую
/// генерацию, либо ждать недоступный хост минутами.
///
/// 10 секунд. Все три адресата — либо `127.0.0.1` (LM Studio, Control Center
/// API), где установление соединения занимает доли миллисекунды, либо
/// Openverse по HTTPS, где на разрешение имени и TLS-рукопожатие уходят
/// сотни миллисекунд (замеры медиа-пайплайна: весь поиск укладывается в
/// единицы секунд). 10 секунд выше любого наблюдавшегося соединения на два
/// порядка и при этом ниже умолчания Windows на повтор SYN (~21 с) — значит
/// отказ по недоступности будет наш и предсказуемый, а не операционной
/// системы и «когда-нибудь».
pub const CONNECT_TIMEOUT: Duration = Duration::from_secs(10);

/// Потолок на ПОЛНЫЙ запрос к LM Studio: 30 минут.
///
/// Выведен из самой долгой наблюдавшейся работы, а не выбран круглым:
///
/// ```text
/// GLM51,      генерация                      630 с   (RESULTS.md, строка 32)
/// Gemma27,    задание 3, прервано человеком  >25 мин (RESULTS.md, строка 28)
/// Gemma27,    задание 2, ru                  508.6 с (gen_gem_ru.txt)
/// Fable9B,    самая долгая из 88 замеров     184.2 с (RESULTS.md, строка 18)
/// ```
///
/// Связывающее число — не 630 с, а те самые «>25 минут»: это реальный
/// рабочий сценарий этого проекта, и он был оборван человеком, а не
/// завершился. Таймаут в 10 или 15 минут превратил бы его в отказ, то есть
/// починка одного дефекта создала бы другой. 1800 с покрывает и его, и
/// вдвое с лишним перекрывает самую долгую ЗАВЕРШИВШУЮСЯ генерацию.
///
/// Чего это число не спасает: 30 минут — всё ещё очень долго для повисшей
/// задачи. Уменьшить его честно можно будет только после того, как
/// генерация станет потоковой (`stream: true`): тогда «сеть висит» отличимо
/// от «модель думает» по факту прихода очередного токена, а не по общему
/// сроку. Сегодня LM Studio на `/v1/chat/completions` не отдаёт ничего до
/// готовности всего ответа, поэтому `read_timeout` здесь неотличим от
/// полного таймаута и смысла не имеет.
pub const LM_STUDIO_TIMEOUT: Duration = Duration::from_secs(1800);

/// Потолок на запрос медиа-пайплайна: 5 минут.
///
/// Клиент обслуживает два вида запросов — поиск в Openverse (страница из
/// `SEARCH_PAGE_SIZE` = 5 записей, ответ в единицы секунд) и скачивание
/// одного ассета. Связывает второе: `fetch::MAX_ASSET_BYTES` = 32 MiB —
/// это потолок, до которого мы обязаны дочитать тело, прежде чем признать
/// файл слишком большим.
///
/// 300 с — это 32 MiB на скорости примерно 0.9 Мбит/с. Скорость канала в
/// этом проекте не измерялась, и число выведено из потолка размера, а не
/// из замера пропускной способности — это допущение, а не факт. Взято с
/// заведомым запасом именно поэтому.
pub const MEDIA_TIMEOUT: Duration = Duration::from_secs(300);

/// Потолок на запрос Telegram Bridge к Control Center API: 30 секунд.
///
/// Оба обращения моста (`POST /tasks`, `GET /tasks/{id}`) — локальные и
/// заведомо быстрые: создание задачи возвращает управление сразу, а сам
/// пайплайн уезжает в `tokio::spawn` и в ответе не участвует; чтение
/// задачи — запрос к SQLite в том же процессе. Здесь не нужен ни один из
/// длинных потолков выше, и ставить их значило бы дать мосту висеть
/// полчаса на ответе, который штатно приходит за миллисекунды.
pub const CONTROL_CENTER_TIMEOUT: Duration = Duration::from_secs(30);

/// Собирает HTTP-клиент с явными таймаутами.
///
/// `connect` ограничивает установление соединения, `response` — весь запрос
/// целиком, включая чтение тела ответа.
///
/// `expect` вместо возврата `Result` — не небрежность: сборка клиента может
/// провалиться только на инициализации TLS-бэкенда, и `reqwest::Client::new()`,
/// который стоял здесь раньше, в этом случае паниковал сам. Поведение при
/// сбое остаётся ровно прежним.
pub fn build(connect: Duration, response: Duration) -> reqwest::Client {
    reqwest::Client::builder()
        .connect_timeout(connect)
        .timeout(response)
        .build()
        .expect("HTTP-клиент собирается: отказать может только инициализация TLS")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn connecting_is_capped_much_sooner_than_answering() {
        // Смысл разделения: недоступный адресат обязан отказать быстро,
        // а работающая генерация — досчитать. Одно число не даёт ни того,
        // ни другого, поэтому инвариант «соединение много короче ответа»
        // фиксируется тестом, а не только комментарием.
        for response in [LM_STUDIO_TIMEOUT, MEDIA_TIMEOUT, CONTROL_CENTER_TIMEOUT] {
            assert!(
                CONNECT_TIMEOUT < response,
                "потолок соединения {CONNECT_TIMEOUT:?} не короче потолка ответа {response:?}"
            );
        }
    }

    #[test]
    fn the_generation_cap_covers_the_longest_run_we_ever_observed() {
        // 25 минут — Gemma27, задание 3 (RESULTS.md): прервано человеком,
        // а не завершилось. Таймаут короче этого превратил бы рабочий
        // сценарий в отказ, что и есть главный риск этой правки.
        assert!(LM_STUDIO_TIMEOUT > Duration::from_secs(25 * 60));
    }
}
